import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:path_provider/path_provider.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:pixlite/main.dart' as app;

void main() {
  final binding=IntegrationTestWidgetsFlutterBinding.ensureInitialized();
  testWidgets('real app startup, processing, language/theme persistence and QR', (tester) async {
    expect(app.pixliteQa,isTrue);
    final output=Directory((await getExternalStorageDirectory())!.path+'/pixlite-qa');
    await output.create(recursive:true);
    await app.main();
    await tester.pumpAndSettle(const Duration(milliseconds:100));
    expect(find.byType(app.HomeScreen),findsOneWidget);
    expect(tester.takeException(),isNull);
    await binding.convertFlutterSurfaceToImage();
    await tester.pump();
    Future<void> shot(String name) async {
      final bytes=await binding.takeScreenshot(name);
      await File(output.path+'/'+name+'.png').writeAsBytes(bytes,flush:true);
    }
    await shot('home-en');
    final result=await tester.runAsync(()=>app.runPixLiteSyntheticQa(output));
    expect(result!['history_persisted'],isTrue);
    expect(result['invalid_image_rejected'],isTrue);
    expect(result['resized_width'],320);
    await tester.pumpAndSettle();
    await tester.tap(find.byType(NavigationDestination).at(2));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Language'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Français'));
    await tester.pumpAndSettle();
    expect((await SharedPreferences.getInstance()).getString('lang'),'fr');
    await shot('settings-fr');
    await tester.tap(find.text('Thème'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Clair'));
    await tester.pumpAndSettle();
    expect((await SharedPreferences.getInstance()).getBool('darkTheme'),isFalse);
    await shot('settings-fr-light');
    await tester.tap(find.text('Langue'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('العربية'));
    await tester.pumpAndSettle();
    expect((await SharedPreferences.getInstance()).getString('lang'),'ar');
    expect(Directionality.of(tester.element(find.byType(app.HomeScreen))),TextDirection.rtl);
    await shot('settings-ar');
    await tester.tap(find.byType(NavigationDestination).at(0));
    await tester.pumpAndSettle();
    await shot('home-ar');
    await tester.tap(find.byType(NavigationDestination).at(2));
    await tester.pumpAndSettle();
    await tester.tap(find.text('اللغة'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('Español'));
    await tester.pumpAndSettle();
    await shot('settings-es');
    await tester.tap(find.text('Idioma'));
    await tester.pumpAndSettle();
    await tester.tap(find.text('English'));
    await tester.pumpAndSettle();
    await tester.pumpWidget(const SizedBox.shrink());
    await app.main();
    await tester.pumpAndSettle();
    expect((await SharedPreferences.getInstance()).getString('lang'),'en');
    expect((await SharedPreferences.getInstance()).getBool('darkTheme'),isFalse);
    expect((await app.OutputStore.list()).any((row)=>row.kind=='PDF'),isTrue);
    await tester.ensureVisible(find.text('QR Code').first);
    await tester.tap(find.text('QR Code').first);
    await tester.pumpAndSettle();
    await tester.enterText(find.byType(TextField).first,'https://example.com/fictional-qa');
    await tester.testTextInput.receiveAction(TextInputAction.done);
    await tester.pumpAndSettle();
    await tester.tap(find.text('Generate QR'));
    await tester.pumpAndSettle();
    expect(find.text('Save / Share'),findsOneWidget);
    expect(tester.takeException(),isNull);
    await shot('qr-generated');
    await File(output.path+'/acceptance.txt').writeAsString(
      'PASS: actual Flutter app, four language views, RTL, light theme, preferences/file history reopen, real image/PDF processing, QR generation. Synthetic data. Native picker/scanner/receiver sharing and physical acceptance remain pending.');
  });
}
